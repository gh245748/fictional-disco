import 'level_curve.dart';

/// Broad groupings of the 99 levels.
enum Band { uyanis, ciraklik, kalfalik, ustalik, ustatlik, pir }

extension BandLabel on Band {
  String get label => switch (this) {
    Band.uyanis => 'Uyanış',
    Band.ciraklik => 'Çıraklık',
    Band.kalfalik => 'Kalfalık',
    Band.ustalik => 'Ustalık',
    Band.ustatlik => 'Üstatlık',
    Band.pir => 'Pir',
  };
}

/// Levels that get a milestone celebration (spec Ek A, starred rows).
const Set<int> milestoneLevels = {10, 25, 50, 75, 99};

Band bandForLevel(int level) {
  if (level >= 99) return Band.pir;
  if (level >= 75) return Band.ustatlik;
  if (level >= 50) return Band.ustalik;
  if (level >= 25) return Band.kalfalik;
  if (level >= 10) return Band.ciraklik;
  return Band.uyanis;
}

